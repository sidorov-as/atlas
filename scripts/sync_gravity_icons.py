def _search_blob(icon: dict) -> str:
    words = [icon["name"], *icon["keywords"], *icon["categories"]]
    return " ".join(dict.fromkeys(word.lower() for word in words if word))


def _write_mcp_output(icons: list[dict], version: str) -> None:
    lines = [_MCP_HEADER.format(version=version)]
    for icon in icons:
        lines.append(f"    ({icon['componentName']!r}, {_search_blob(icon)!r}),\n")
    lines.append(")\n")
    _MCP_OUTPUT.write_text("".join(lines), encoding="utf-8")


def _write_flows_output(icons: list[dict], version: str) -> None:
    lines = [_FLOWS_HEADER.format(version=version)]
    for icon in icons:
        lines.append(f"        {icon['componentName']!r},\n")
    lines.append(_FLOWS_FOOTER)
    _FLOWS_OUTPUT.write_text("".join(lines), encoding="utf-8")


def main() -> None:
    package_json = json.loads(
        (_SOURCE.parent / "package.json").read_text(encoding="utf-8")
    )
    version = package_json["version"]
    icons = json.loads(_SOURCE.read_text(encoding="utf-8"))["icons"]

    _write_mcp_output(icons, version)
    _write_flows_output(icons, version)

    print(f"Wrote {len(icons)} icons to {_MCP_OUTPUT}")
    print(f"Wrote {len(icons)} icons to {_FLOWS_OUTPUT}")


if __name__ == "__main__":
    main()
