#!/usr/bin/env python3
"""Regenerates two vendored, checked-in copies of `@gravity-ui/icons`' own
`metadata.json` — the same file `plugins/flows/frontend/src/lib/
gravityIcons.ts` reads client-side to validate a Flow step's `icon` field
and power its icon picker:

- `mcp/atlas_mcp/_gravity_icons.py`: name + searchable keyword/category
  blob, for the `search_flow_icons` MCP tool (`mcp/atlas_mcp/icons.py`) to
  match a free-text query against.
- `plugins/flows/backend/atlas_plugin_flows/_gravity_icons.py`: a flat name
  set, for `atlas_plugin_flows.api.step_schemas.StepIn` to validate a
  submitted `icon` value against at write time.

Both processes are pure Python with no JS runtime and no npm dependency of
their own (`mcp/atlas_mcp/server.py`'s own docstring: "this process holds no
Django import ... extends to not holding a node_modules dependency"; the
same is true in reverse for the Django backend never importing from
`node_modules`). Rather than shelling out to Node at import time, or
fetching the npm package over the network at startup, this script is a
one-off, manually-run sync: it reads the copy of `@gravity-ui/icons`
already installed at the repo root (a peer dependency of
`plugins/flows/frontend`) and writes two small, static Python modules — no
different in spirit from committing a lockfile.

Run this after bumping `@gravity-ui/icons` in `plugins/flows/frontend`'s
`package.json` (from the repo root, with `node_modules` installed):

    python scripts/sync_gravity_icons.py

It only ever touches the two generated files above — verify the diff (an
icon rename/removal is possible, if rare) before committing.
"""

